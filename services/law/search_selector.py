# ============================================================
# 검색 결과에서 법령 선택
#
# 기존 규칙 유지
#
# 1. 법령명 완전 일치
# 2. 검색어가 법령명에 포함
# 3. 첫 번째 결과 fallback
# ============================================================


def select_exact_law(
    law_name: str,
    laws: list
):

    law_name = (
        law_name
        or ""
    ).strip()

    if not law_name:
        return None

    if not laws:
        return None

    # ========================================================
    # 1. 완전 일치
    # ========================================================

    for law in laws:

        result_name = str(
            law.get(
                "법령명한글",
                ""
            )
        ).strip()

        if result_name == law_name:
            return law

    # ========================================================
    # 2. 검색어가 법령명에 포함
    # ========================================================

    for law in laws:

        result_name = str(
            law.get(
                "법령명한글",
                ""
            )
        ).strip()

        if (
            law_name
            and
            law_name in result_name
        ):

            return law

    # ========================================================
    # 3. fallback
    # ========================================================

    return laws[0]