def compact(text):
    return re.sub(r"\s+", "", str(text or "")).lower()


def match_profiles(question):
    text = compact(question)
    matched = [p for p in PROFILES if all(any(compact(term) in text for term in group) for group in p["triggers"])]

    def add_context(identifier, terms, laws, questions):
        matched.append(dict(id=identifier, terms=terms, laws=laws, questions=questions))

    defenses = tuple(t for t in ("정당방위", "긴급피난", "정당행위", "심신장애") if t in text)
    if defenses:
        add_context("criminal_defenses", defenses, {"형법": tuple((t,) for t in defenses)},
                    ("위법성·책임을 배제하는 요건을 실제 사실관계와 대조해야 합니다. 해당 표현을 썼다는 이유만으로 면책을 확정하지 않습니다.",))
    criminal_context = any("형법" in p["laws"] or p["id"] in {"drink_driving", "unlicensed"} for p in matched) or "형사처벌" in text
    if criminal_context and (re.search(r"\d{1,2}(?:살|세)", text) or any(t in text for t in ("미성년", "촉법", "소년"))):
        add_context("criminal_age", ("형사미성년자",), {"형법": (("형사미성년자",),), "소년법": (("보호", "대상"),)},
                    ("행위 당시의 정확한 나이와 생년월일을 확인해야 합니다. 형사처벌과 소년 보호처분은 구분합니다.",))
    if any("근로기준법" in p["laws"] for p in matched) and ("상시" in text or re.search(r"\d+명|\d+인사업장", text)):
        add_context("workplace_scope", ("근로기준법 적용 범위",),
                    {"근로기준법": (("적용", "범위"),), "근로기준법 시행령": (("적용", "범위"),)},
                    ("상시 근로자 수의 산정과 시행령 별표의 적용 조항까지 확인해야 합니다.",))
    if any(p["id"] == "drink_driving" for p in matched) and any(t in text for t in ("다치", "다쳤", "상해", "사망", "죽", "사고")):
        add_context("driving_injury", ("위험운전 치사상",),
                    {"특정범죄 가중처벌 등에 관한 법률": (("위험운전", "치사상"),), "교통사고처리 특례법": (("처벌", "특례"),)},
                    ("음주 사실과 정상적인 운전이 곤란한 상태는 같은 요건이 아닙니다. 운전 상태·피해·인과관계 등 추가 사실을 확인해야 합니다.",))
    return matched


def search_hints(question):
    profiles = match_profiles(question)

    # 사람이 검토한 평이한 요약 (summary 필드가 있는 profile만)
    summaries = [
        p["summary"]
        for p in profiles
        if isinstance(p.get("summary"), str) and p["summary"].strip()
    ]

    # 판례 검색 전용 쿼리 (profile.precedent_query 있으면 우선)
    precedent_queries = [
        p["precedent_query"]
        for p in profiles
        if isinstance(p.get("precedent_query"), str) and p["precedent_query"].strip()
    ]

    # profile별 선호 판례 사건종류 (순서 유지, 중복 제거)
    preferred_case_types = []
    for p in profiles:
        for ct in PROFILE_CASE_TYPES.get(p["id"], []):
            if ct not in preferred_case_types:
                preferred_case_types.append(ct)

    return {
        "profile_ids": [p["id"] for p in profiles],
        "terms": list(dict.fromkeys(t for p in profiles for t in p["terms"])),
        "law_names": list(dict.fromkeys(law for p in profiles for law in p["laws"])),
        "summaries": summaries,
        "precedent_queries": precedent_queries,
        "preferred_case_types": preferred_case_types,
    }
