# ============================================================

def normalize_text(
    text
):

    if text is None:

        return ""

    return str(
        text
    ).strip()


# ============================================================
# 2. 리스트 형태 보장
# ============================================================

def ensure_list(
    value
):

    if value is None:

        return []

    if isinstance(
        value,
        list
    ):

        return value

    if isinstance(
        value,
        dict
    ):

        return [
            value
        ]

    return []