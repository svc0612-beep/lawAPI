# 6. API 검색용 검색어 생성
# ============================================================

def make_search_query(
    question: str,
    law_name
):

    """
    이후 법제처 API에 전달할
    기본 검색어를 만든다.
    """

    # --------------------------------------------------------
    # 정확한 법령명이 있으면
    # 법령명 자체를 검색한다.
    # --------------------------------------------------------

    if law_name:

        return law_name


    # --------------------------------------------------------
    # 법령명이 없는 자연어 질문
    #
    # 불필요한 질문 표현을 제거해서
    # 핵심 검색어를 남긴다.
    # --------------------------------------------------------

    search_query = question


    remove_words = [
        "알려줘",
        "알려 줘",
        "보여줘",
        "보여 줘",
        "찾아줘",
        "찾아 줘",
        "설명해줘",
        "설명해 줘",
        "뭐야",
        "뭐지",
        "무엇이야",
        "무슨 법",
        "어떤 법",
        "관련 법",
        "관련법",
        "어떻게 돼",
        "어떻게 되",
        "어떻게 되는지",
    ]


    for word in remove_words:

        search_query = (
            search_query.replace(
                word,
                " "
            )
        )


    # --------------------------------------------------------
    # 의미가 약한 조사/표현 일부 제거
    # --------------------------------------------------------

    search_query = re.sub(
        r"\s+",
        " ",
        search_query
    ).strip()


    return search_query


# ============================================================
# 7. 최종 질문 분석
# ============================================================

def analyze_question(question: str):

    """
    사용자 질문을 구조화한다.
    """

    question = question.strip()


    # --------------------------------------------------------
    # 법령명
    # --------------------------------------------------------

    law_name = extract_law_name(
        question
    )


    # --------------------------------------------------------
    # 조
    # --------------------------------------------------------

    article_info = (
        extract_article_number(
            question
        )
    )

    article_number = (
        article_info[
            "article_number"
        ]
    )

    sub_article_number = (
        article_info[
            "sub_article_number"
        ]
    )


    # --------------------------------------------------------
    # 항
    # --------------------------------------------------------

    paragraph_number = (
        extract_paragraph_number(
            question
        )
    )


    # --------------------------------------------------------
    # 질문 유형
    # --------------------------------------------------------

    question_type = (
        classify_question(
            question,
            law_name,
            article_number
        )
    )


    # --------------------------------------------------------
    # 검색어
    # --------------------------------------------------------

    search_query = (
        make_search_query(
            question,
            law_name
        )
    )


    return {

        "original_question":
            question,

        "question_type":
            question_type,

        "law_name":
            law_name,

        "article_number":
            article_number,

        "sub_article_number":
            sub_article_number,

        "paragraph_number":
            paragraph_number,

        "search_query":
            search_query,
    }


