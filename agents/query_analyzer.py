# ============================================================
# 1. 대표적인 법령명 별칭
# ============================================================
#
# 사용자가 흔히 사용하는 표현을
# 실제 법령명으로 보정한다.
#
# 이 목록에 대한민국 법령 전체를 넣는 것이 아니다.
# 나중에 실제 법령 존재 여부는 법제처 API가 판단한다.
# ============================================================

